export function removeCustom(id) {
  writeKey('rq27.custom', getCustom().filter((q) => q.id !== id));
  invalidate();
}
export function setHidden(id, hidden) {
  const s = new Set(getSettings().hiddenIds || []);
  hidden ? s.add(id) : s.delete(id);
  setSettings({ hiddenIds: [...s] });
  invalidate();
}

let cache = null;
export function invalidate() { cache = null; }

/** البنك الفعّال (بعد إخفاء الأسئلة المحذوفة) */
export function getBank() {
  if (cache) return cache;
  const hidden = new Set(getSettings().hiddenIds || []);
  cache = [...STARTER, ...getRemote(), ...getCustom()].filter((q) => !hidden.has(q.id) && isValid(q));
  return cache;
}
export const getStarter = () => STARTER;
export const allQuestions = () => [...STARTER, ...getRemote(), ...getCustom()];

export function isValid(q) {
  return q && typeof q.q === 'string' && Array.isArray(q.a) && q.a.length === 4 && Number.isInteger(q.c) && q.c >= 0 && q.c < 4 && [1, 2, 3].includes(q.diff);
}

export function bankStats() {
  const b = getBank();
  return { total: b.length, d1: b.filter((q) => q.diff === 1).length, d2: b.filter((q) => q.diff === 2).length, d3: b.filter((q) => q.diff === 3).length };
}

/** يقبل: مصفوفة بصيغتنا، أو بصيغة المشروع القديم {q, options, correctIndex}، أو مستند quizzes_pool كامل */
export function normalizeImport(data) {
  const out = [];
  const pushOne = (o, fallbackDiff = 2) => {
    if (!o) return;
    const a = o.a || o.options;
    const c = o.c ?? o.correctIndex;
    const q = { cat: CATS[o.cat] ? o.cat : 'general', diff: [1, 2, 3].includes(o.diff) ? o.diff : fallbackDiff, q: String(o.q || '').trim(), a: Array.isArray(a) ? a.map(String) : [], c: Number(c), e: String(o.e || o.explanation || '') };
    if (isValid(q)) out.push(q);
  };
  const walk = (x) => {
    if (Array.isArray(x)) x.forEach((i) => (i && (i.q || i.options) ? pushOne(i) : walk(i)));
    else if (x && typeof x === 'object') {
      if (x.variations) {
        Object.values(x.variations).forEach((v) => (v.questions || []).forEach((i) => pushOne(i)));
      } else if (x.questions) walk(x.questions);
      else Object.values(x).forEach(walk);
    }
  };
  walk(data);
  return out;
}

export function importQuestions(list) {
  const cur = getCustom();
  const seen = new Set([...STARTER, ...cur].map((q) => q.q));
  let added = 0;
  for (const q of list) {
    if (seen.has(q.q)) continue;
    seen.add(q.q);
    cur.push({ ...q, id: 'c' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6) });
    added++;
  }
  writeKey('rq27.custom', cur);
  invalidate();
  return added;
}
